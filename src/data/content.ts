function countWords(lang: Lang, falseFriend: boolean) {
  return words.filter((word) => word.lang === lang && (word.tipType === 'falseFriend') === falseFriend).length;
}

if (countWords('es', false) !== 15 || countWords('de', false) !== 15) {
  throw new Error('Expected 15 cognate cards per language');
}
if (countWords('es', true) < 3 || countWords('de', true) < 3) {
  throw new Error('Expected false-friend cards in both languages');
}
if (sentences.filter((sentence) => sentence.lang === 'es').length !== 10) {
  throw new Error('Expected 10 Spanish sentences');
}
if (sentences.filter((sentence) => sentence.lang === 'de').length !== 10) {
  throw new Error('Expected 10 German sentences');
}

